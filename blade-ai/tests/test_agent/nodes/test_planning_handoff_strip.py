"""Planning handoff strip — the phase-handoff-context-stripping pinning suite.

Covers the spec's core scenarios with pure-function tests over
``select_strip_targets`` / ``planning_handoff`` plus REAL ``add_messages``
reducer runs for the deletion semantics (RemoveMessage by id), the replan
full-loop (two rounds, each strip bounded by its own attribution epoch),
the compaction interaction (both orderings), the kickoff-scan
compatibility, and the replica-fallback survival in the retained zone.

The anchor whitelist contract under test:
- anchors (FAULT INTENT, probe hints) are marked at GENERATION time and
  survive the strip;
- everything else inside [attribution_epoch_index, finalized) is removed
  — AI turns, tool results, in-loop corrective feedback;
- messages before the epoch boundary (prior rounds' finalized markers,
  kickoffs, execution receipts, verification evidence) are the replan's
  input and are never removed;
- the finalized marker and everything after it are retained;
- persist-then-remove ordering with skip-on-failure (archive first).
"""

