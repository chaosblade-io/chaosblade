class TestPlanningHandoffNode:
    def _state(self, seq, epoch=None):
        state = {"messages": list(seq), "task_id": TASK_ID}
        if epoch is not None:
            state["attribution_epoch_index"] = epoch
        return state

    def test_no_finalized_marker_no_state_change(self, monkeypatch):
        _patch_store(monkeypatch, _FakeStore())
        seq = [_anchor_fault_intent(), _anchor_probe_hints(), _ai_probe_turn("c1", "nodes")]
        assert planning_handoff(self._state(seq)) == {}

    def test_returns_only_messages_key_epoch_untouched(self, monkeypatch):
        # The invariant's first half: the node's state update never carries
        # attribution_epoch_index — the reducer leaves it numerically
        # unchanged because the strip only removes AFTER the boundary.
        _patch_store(monkeypatch, _FakeStore())
        seq = _first_pass_sequence()
        result = planning_handoff(self._state(seq, epoch=0))
        assert set(result.keys()) == {"messages"}
        assert "attribution_epoch_index" not in result

    def test_persist_then_remove_ordering(self, monkeypatch):
        # Archive BEFORE removal: the store receives the ORIGINAL messages
        # (not RemoveMessage wrappers), and the returned removals match
        # exactly those ids.
        store = _FakeStore()
        _patch_store(monkeypatch, store)
        seq = _first_pass_sequence()
        result = planning_handoff(self._state(seq))

        assert len(store.appends) == 1
        task_id, archived, node_name = store.appends[0]
        assert task_id == TASK_ID
        assert node_name == "planning_handoff"
        removal_ids = {r.id for r in result["messages"]}
        assert removal_ids == {m.id for m in archived}
        # No RemoveMessage reaches the archive path.
        from langchain_core.messages import RemoveMessage
        assert not any(isinstance(m, RemoveMessage) for m in archived)
        # Anchors are neither archived (they are not stripped) nor removed.
        assert seq[0].id not in removal_ids
        assert seq[1].id not in removal_ids

    def test_idempotent_reentry_after_reducer_application(self, monkeypatch):
        # Positional idempotency: apply the removals via the REAL reducer,
        # re-run the node → nothing left to do.
        _patch_store(monkeypatch, _FakeStore())
        seq = _first_pass_sequence()
        state = self._state(seq, epoch=0)

        first = planning_handoff(state)
        assert first, "first pass must strip"

        state["messages"] = add_messages(state["messages"], first["messages"])
        second = planning_handoff(state)
        assert second == {}

    def test_persistence_failure_skips_strip(self, monkeypatch):
        _patch_store(monkeypatch, _FailingStore())
        seq = _first_pass_sequence()
        assert planning_handoff(self._state(seq)) == {}

    def test_silent_missing_session_skips_strip(self, monkeypatch):
        # append_messages returns NORMALLY when the task has no active
        # session ("Task not found, skipping append") — no exception is
        # ever raised. Only the read-back catches it.
        store = _SilentSwallowStore(read_result=None)
        _patch_store(monkeypatch, store)
        seq = _first_pass_sequence()
        assert planning_handoff(self._state(seq)) == {}
        assert store.appends, "append was attempted (and silently dropped)"

    def test_silent_disk_write_failure_skips_strip(self, monkeypatch):
        # Round-5 audit: append_messages swallows disk-write failures on
        # purpose (fire-and-forget archival contract). The read-back
        # reads from disk, so the swallowed write reads back as missing.
        from chaos_agent.memory.session_store import _serialize_message_full

        seq = _first_pass_sequence()
        # Disk snapshot exists but holds only the anchors — the strip's
        # write never landed.
        disk = {"messages": [_serialize_message_full(seq[0]),
                              _serialize_message_full(seq[1])]}
        store = _SilentSwallowStore(read_result=disk)
        _patch_store(monkeypatch, store)
        assert planning_handoff(self._state(seq)) == {}
        assert store.appends, "append was attempted (and silently dropped)"

    def test_readback_covers_preexisting_archive(self, monkeypatch):
        # Dedup semantics: messages the pre_reason_hook flush already
        # archived are skipped by append_messages but MUST read back as
        # present — the strip proceeds for the full target set (the
        # pre-existing entries simply dedup out of the append).
        seq = _first_pass_sequence()
        store = _FakeStore(preexisting=[seq[2], seq[3]])  # flushed earlier
        _patch_store(monkeypatch, store)
        result = planning_handoff(self._state(seq))
        assert result and len(result["messages"]) == 5
        appended_ids = {m.id for _, msgs, _ in store.appends for m in msgs}
        assert appended_ids == {seq[i].id for i in (2, 3, 4, 5, 6)}

    def test_no_task_id_skips_strip(self, monkeypatch):
        _patch_store(monkeypatch, _FakeStore())
        seq = _first_pass_sequence()
        assert planning_handoff({"messages": list(seq)}) == {}

    def test_no_store_skips_strip(self, monkeypatch):
        _patch_store(monkeypatch, None)
        seq = _first_pass_sequence()
        assert planning_handoff(self._state(seq)) == {}


