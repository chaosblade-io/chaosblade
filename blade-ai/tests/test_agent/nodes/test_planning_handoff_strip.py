class TestKickoffScanCompat:
    def test_kickoff_scan_semantics_unchanged_across_strip(self, monkeypatch):
        # _phase2_kickoff_needed reverse-scans for the LAST finalized
        # marker — the strip leaves it (and everything after) intact, so
        # the positional scan returns the SAME verdict before and after
        # the strip, both when armed (no kickoff after finalized) and
        # when already announced (kickoff present).
        from chaos_agent.agent.nodes.execute.execute_loop import (
            _phase2_kickoff_needed,
        )

        _patch_store(monkeypatch, _FakeStore())

        # Armed case: finalized but no kickoff/productive AI after it.
        seq = list(add_messages([], [
            _anchor_fault_intent(),
            _anchor_probe_hints(),
            _ai_probe_turn("c1", "nodes"),
            _tool_result("c1", "..."),
            _finalized(),
            _verify_turn(),
        ]))
        state = {"messages": list(seq), "task_id": TASK_ID}
        assert _phase2_kickoff_needed(state["messages"]) is True

        result = planning_handoff(state)
        state["messages"] = add_messages(state["messages"], result["messages"])
        # Finalized marker still located, still the newest signal → armed.
        assert _phase2_kickoff_needed(state["messages"]) is True

        # Once the kickoff lands (execute_loop emits it), the scan disarms —
        # the message stays in the retained zone.
        state["messages"] = add_messages(state["messages"], [_kickoff()])
        assert _phase2_kickoff_needed(state["messages"]) is False

    def test_kickoff_marker_survives_strip(self, monkeypatch):
        # The full first-pass sequence already carries a kickoff in the
        # retained zone: after the strip it is still there, still disarming
        # the scan (kickoff semantics unchanged).
        from chaos_agent.agent.nodes.execute.execute_loop import (
            _phase2_kickoff_needed,
        )

        _patch_store(monkeypatch, _FakeStore())
        seq = _first_pass_sequence()
        state = {"messages": list(seq), "task_id": TASK_ID}
        assert _phase2_kickoff_needed(state["messages"]) is False

        result = planning_handoff(state)
        state["messages"] = add_messages(state["messages"], result["messages"])
        assert _phase2_kickoff_needed(state["messages"]) is False
        surviving_ids = [m.id for m in state["messages"]]
        assert seq[8].id in surviving_ids  # the kickoff itself


