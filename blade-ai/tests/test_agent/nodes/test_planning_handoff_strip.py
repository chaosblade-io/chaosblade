class TestReducerSemantics:
    def test_removals_delete_by_id_via_real_reducer(self, monkeypatch):
        _patch_store(monkeypatch, _FakeStore())
        seq = _first_pass_sequence()
        state = {"messages": list(seq), "task_id": TASK_ID}

        result = planning_handoff(state)
        stripped = add_messages(state["messages"], result["messages"])

        surviving_ids = [m.id for m in stripped]
        assert seq[2].id not in surviving_ids  # AI probe turn
        assert seq[3].id not in surviving_ids  # tool result
        assert seq[6].id not in surviving_ids  # RUNTIME EVIDENCE hint
        # Order and content of survivors preserved (anchors + finalized +
        # downstream).
        assert [m.id for m in stripped] == [
            seq[0].id, seq[1].id, seq[7].id, seq[8].id, seq[9].id, seq[10].id,
        ]

    def test_two_replan_rounds_strip_only_own_round(self, monkeypatch):
        """3.4 replan full loop: each handoff strips its own planning round;
        prior rounds' execution/verification evidence survives as the
        replan's input; attribution never resurrects pre-seam attempts.
        The three seam sites (execute_loop / plan_change_confirm /
        _verifier_finalize) are graph-wired back into agent_loop (pinned
        in test_graph_invariants), so this semantics test plus that
        topology pinning covers all three replan paths."""
        store = _FakeStore()
        _patch_store(monkeypatch, store)

        round1 = _first_pass_sequence()  # 11 messages, finalized at idx 7
        state = {"messages": list(round1), "task_id": TASK_ID}

        # Handoff 1: strips round-1 planning (idx 2..6).
        h1 = planning_handoff(state)
        state["messages"] = add_messages(state["messages"], h1["messages"])
        epoch1 = len(state["messages"])  # seam lands at the current length

        # Verify failure → replan seam resets the attribution epoch.
        state["attribution_epoch_index"] = epoch1

        # Round 2 planning (replan): fresh probe turns + feedback.
        round2 = list(add_messages([], [
            _ai_probe_turn("c3", "describe node worker-1"),
            _tool_result("c3", "Allocatable: 16Gi"),
            _runtime_evidence_hint(),
            _finalized("round 2 plan — fallback to native"),
            _kickoff(),
            _exec_receipt(),
            _verify_turn(),
        ]))
        state["messages"] = add_messages(state["messages"], round2)

        # Handoff 2: strips ONLY round-2 planning (the new epoch range).
        h2 = planning_handoff(state)
        assert h2, "round-2 strip must fire"
        removal2_ids = {r.id for r in h2["messages"]}
        assert removal2_ids == {round2[0].id, round2[1].id, round2[2].id}

        state["messages"] = add_messages(state["messages"], h2["messages"])

        surviving = [m.id for m in state["messages"]]
        # Round-1 anchors, finalized, kickoff, receipt, verify survive.
        for i in (0, 1, 7, 8, 9, 10):
            assert round1[i].id in surviving
        # Round-1 planning turns are gone.
        for i in (2, 3, 4, 5, 6):
            assert round1[i].id not in surviving
        # Round-2 finalized/kickoff/receipt/verify survive.
        for m in round2[3:]:
            assert m.id in surviving

        # 2.4 archive pinning: BOTH stripped planning rounds are in the
        # task JSON — two persist batches, together carrying every removed
        # message (dedup-key idempotence in the real store absorbs the
        # hook-flush double writes).
        assert len(store.appends) == 2
        archived_ids = {m.id for _, batch, _ in store.appends for m in batch}
        assert archived_ids == {
            round1[i].id for i in (2, 3, 4, 5, 6)
        } | {round2[i].id for i in (0, 1, 2)}

    def test_epoch_index_invariance_across_strip(self, monkeypatch):
        """3.2 invariance: epoch value unchanged; the epoch-bounded slice
        consumed by attribution scans keeps its execution evidence intact
        (the strip only removes planning turns inside the range)."""
        _patch_store(monkeypatch, _FakeStore())
        seq = _first_pass_sequence()
        epoch = 0
        state = {
            "messages": list(seq),
            "task_id": TASK_ID,
            "attribution_epoch_index": epoch,
        }

        result = planning_handoff(state)
        assert "attribution_epoch_index" not in result
        state["messages"] = add_messages(state["messages"], result["messages"])

        assert state["attribution_epoch_index"] == epoch
        # The epoch slice still carries the execution receipt + verify turn
        # (attribution scans read ToolMessages like blade_create receipts).
        slice_msgs = state["messages"][state["attribution_epoch_index"]:]
        slice_ids = {m.id for m in slice_msgs}
        assert seq[9].id in slice_ids  # blade_create receipt
        assert seq[10].id in slice_ids  # verification turn


