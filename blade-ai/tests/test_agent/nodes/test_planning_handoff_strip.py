class _FakeStore:
    """Happy-path store: appends land and read back like a healthy disk."""

    def __init__(self, preexisting=None):
        self.appends: list[tuple[str, list, str]] = []
        self._preexisting = list(preexisting or [])

    def append_messages(self, task_id, messages, node_name=""):
        self.appends.append((task_id, list(messages), node_name))

    def read_session(self, task_id):
        from chaos_agent.memory.session_store import _serialize_message_full

        archived = list(self._preexisting)
        for _, msgs, _node in self.appends:
            archived.extend(msgs)
        return {"messages": [_serialize_message_full(m) for m in archived]}


class _FailingStore:
    def append_messages(self, task_id, messages, node_name=""):
        raise OSError("disk full")


class _SilentSwallowStore:
    """Mirrors the REAL fire-and-forget contract: append_messages returns
    normally even when nothing landed (missing active session, swallowed
    disk-write failure). Exception-based guards see success here; only
    the read-back verification can tell the difference."""

    def __init__(self, read_result=None):
        self.appends: list[tuple[str, list, str]] = []
        self._read_result = read_result  # None → task unknown

    def append_messages(self, task_id, messages, node_name=""):
        self.appends.append((task_id, list(messages), node_name))

    def read_session(self, task_id):
        return self._read_result


def _patch_store(monkeypatch, store):
    import chaos_agent.memory.session_store as ss

    monkeypatch.setattr(ss, "get_global_session_store", lambda: store)


