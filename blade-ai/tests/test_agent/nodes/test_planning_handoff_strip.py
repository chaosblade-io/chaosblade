class TestCompactionInteraction:
    def test_handoff_then_compaction(self, monkeypatch):
        # Handoff removes AFTER the epoch boundary and leaves the index;
        # compaction then removes BEFORE the boundary and re-bases. The
        # two mechanisms never delete from the same side — the re-base
        # counts survivors before the boundary, and the handoff deleted
        # none of those, so the arithmetic stays correct.
        from chaos_agent.memory.hook import _rebase_epoch_index

        _patch_store(monkeypatch, _FakeStore())

        # Two-round state: round-1 already handoff-stripped.
        seq = _first_pass_sequence()
        state = {"messages": list(seq), "task_id": TASK_ID}
        h1 = planning_handoff(state)
        state["messages"] = add_messages(state["messages"], h1["messages"])
        epoch = len(state["messages"])  # replan seam lands at this length
        state["attribution_epoch_index"] = epoch

        # Compaction removes pre-boundary messages (say the round-1 kickoff
        # and receipt — summaries replace them) and re-bases.
        pre_boundary = state["messages"][:epoch]
        to_compact = [m for m in pre_boundary if isinstance(m, ToolMessage)]
        removed_ids = {m.id for m in to_compact}
        state["messages"] = [
            m for m in state["messages"] if m.id not in removed_ids
        ]
        rebased = _rebase_epoch_index(state["messages"], to_compact, epoch)
        assert rebased is not None and rebased < epoch
        state["attribution_epoch_index"] = rebased

        # The epoch slice stays semantically valid: everything from the
        # rebased boundary onward is the post-seam history, intact.
        slice_ids = {m.id for m in state["messages"][rebased:]}
        assert not slice_ids & removed_ids

    def test_compaction_then_handoff(self, monkeypatch):
        # Compaction first: it removes pre-boundary messages and re-bases
        # the epoch index; the handoff's positional rules then locate the
        # finalized marker on the COMPACTED list and strip the new round.
        _patch_store(monkeypatch, _FakeStore())

        # Two-round sequence without any prior handoff strip.
        seq = list(add_messages([], [
            _anchor_fault_intent(),        # 0
            _anchor_probe_hints(),         # 1
            _ai_probe_turn("c1", "nodes"),  # 2
            _tool_result("c1", "..."),     # 3
            _finalized("round 1"),         # 4
            _kickoff(),                    # 5
            _exec_receipt(),               # 6
            _verify_turn(),                # 7
            _ai_probe_turn("c3", "..."),   # 8  (round 2 planning)
            _tool_result("c3", "..."),     # 9
            _finalized("round 2"),         # 10
        ]))
        state = {"messages": list(seq), "task_id": TASK_ID}
        state["attribution_epoch_index"] = 8

        # Compaction removes the pre-boundary planning turns (2, 3) and
        # re-bases the epoch from 8 to 6. The re-base counts survivors in
        # the PRE-deletion list — pass the original sequence.
        to_compact = [seq[2], seq[3]]
        removals = {m.id for m in to_compact}
        state["messages"] = [
            m for m in state["messages"] if m.id not in removals
        ]
        from chaos_agent.memory.hook import _rebase_epoch_index
        rebased = _rebase_epoch_index(seq, to_compact, 8)
        assert rebased == 6
        state["attribution_epoch_index"] = rebased

        # Handoff on the compacted list: range [6, finalized=8) still
        # selects exactly the round-2 planning turns.
        result = planning_handoff(state)
        assert {r.id for r in result["messages"]} == {seq[8].id, seq[9].id}


