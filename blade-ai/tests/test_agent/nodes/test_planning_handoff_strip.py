class TestSelectStripTargets:
    """Anchor whitelist inside the epoch-bounded range."""

    def test_anchors_retained_process_messages_stripped(self):
        seq = _first_pass_sequence()
        finalized_idx = _find_finalized_idx(seq)
        targets = select_strip_targets(seq, 0, finalized_idx)

        target_ids = {t.id for t in targets}
        # Anchors survive.
        assert seq[0].id not in target_ids  # FAULT INTENT
        assert seq[1].id not in target_ids  # probe hints
        # Finalized and everything after survive.
        for m in seq[finalized_idx:]:
            assert m.id not in target_ids
        # The planning round's process messages are stripped: AI turns,
        # tool results, in-loop corrective feedback.
        for m in seq[2:finalized_idx]:
            assert m.id in target_ids
        assert len(targets) == finalized_idx - 2

    def test_finalization_caller_exempt_from_strip(self):
        """B44: the finish_planning caller must survive the strip.

        Stripping the caller orphaned the retained ``Planning finalized``
        ToolMessage — sanitize_tool_pairing then dropped that orphan
        before EVERY downstream LLM call (case-32: six drops across the
        inject and recover graphs), so the summary the strip meant to
        hand to execution never reached a model.
        """
        seq = list(add_messages([], [
            _anchor_fault_intent(),               # 0
            _ai_probe_turn("c1", "nodes"),        # 1
            _tool_result("c1", "NAME STATUS"),    # 2
            _finish_planning_caller(),            # 3 — caller of finalized
            _finalized(),                         # 4
            _kickoff(),                           # 5
        ]))
        finalized_idx = _find_finalized_idx(seq)
        assert finalized_idx == 4

        targets = select_strip_targets(seq, 0, finalized_idx)
        target_ids = {t.id for t in targets}

        # Probe turn still stripped.
        assert seq[1].id in target_ids
        assert seq[2].id in target_ids
        # The caller is exempt: finalized keeps its AIMessage pair.
        assert seq[3].id not in target_ids

    def test_parallel_finalization_batch_tool_results_exempt(self):
        """A parallel finish_planning + probe turn keeps its whole batch paired.

        Exempting only the caller AIMessage would trade one orphan for
        another when the finalization turn carried sibling tool_calls
        whose ToolMessages land inside the strip range.
        """
        seq = list(add_messages([], [
            _anchor_fault_intent(),               # 0
            _finish_planning_caller("call-finish", extra_calls=[{
                "name": "kubectl",
                "args": {"subcommand": "get", "v_args": "nodes"},
                "id": "c9",
                "type": "tool_call",
            }]),                                 # 1 — batch of 2 calls
            _tool_result("c9", "NAME STATUS"),    # 2 — sibling result in range
            _finalized(),                         # 3
        ]))
        finalized_idx = _find_finalized_idx(seq)
        assert finalized_idx == 3

        targets = select_strip_targets(seq, 0, finalized_idx)
        target_ids = {t.id for t in targets}

        # Whole finalization batch survives: caller + sibling result.
        assert seq[1].id not in target_ids
        assert seq[2].id not in target_ids
        assert targets == []

    def test_epoch_boundary_excludes_prior_round_evidence(self):
        # Replan scenario: round-1 execution/verification evidence sits
        # BEFORE the epoch boundary and must survive the round-2 strip.
        seq = list(add_messages([], [
            _anchor_fault_intent(),       # 0
            _anchor_probe_hints(),        # 1
            _ai_probe_turn("c1", "nodes"),  # 2  (round 1 planning)
            _tool_result("c1", "..."),    # 3
            _finalized("round 1 plan"),   # 4
            _kickoff(),                   # 5
            _exec_receipt(),              # 6
            _verify_turn(),               # 7
            # ── replan seam: epoch reset here → epoch = 8 ──
            _ai_probe_turn("c3", "describe node worker-1"),  # 8 (round 2)
            _tool_result("c3", "..."),    # 9
            _runtime_evidence_hint(),     # 10
            _finalized("round 2 plan"),   # 11
            _kickoff(),                   # 12
            _exec_receipt(),              # 13
        ]))
        epoch = 8
        finalized_idx = _find_finalized_idx(seq)
        assert finalized_idx == 11

        targets = select_strip_targets(seq, epoch, finalized_idx)
        target_ids = {t.id for t in targets}

        # Round-2 planning messages (8..10) stripped.
        for m in seq[epoch:finalized_idx]:
            assert m.id in target_ids
        # Round-1 evidence BEFORE the boundary survives: old finalized,
        # kickoff, execution receipt, verification turn, plus anchors.
        for m in seq[:epoch]:
            assert m.id not in target_ids
        # New finalized and after survive.
        for m in seq[finalized_idx:]:
            assert m.id not in target_ids

    def test_epoch_at_or_after_finalized_selects_nothing(self):
        # Batch iteration with a stale durable epoch: boundary lands at or
        # after the new marker → empty range, fail-safe toward keeping.
        seq = [_finalized(), _kickoff()]
        assert select_strip_targets(seq, 5, 0) == []
        assert select_strip_targets(seq, 2, 0) == []

    def test_idless_messages_never_selected(self):
        ai = AIMessage(content="thinking")  # no id
        finalized = _finalized()
        seq = [ai, finalized]
        targets = select_strip_targets(seq, 0, 1)
        assert targets == []

    def test_negative_or_none_finalized_selects_nothing(self):
        assert select_strip_targets([_finalized()], 0, None) == []


