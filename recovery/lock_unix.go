package recovery

import (
	"context"
	"errors"
	"os"
	"path/filepath"
	"syscall"
	"time"
)

// A single local effect lock deliberately bounds concurrency. SQLite is never
// held across a subprocess; emergency stop intent can be persisted immediately.
func (m *Manager) lock(ctx context.Context) (func(), error) {
	f, err := os.OpenFile(filepath.Join(m.dir, "recovery.lock"), os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, err
	}
	for {
		err = syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB)
		if err == nil {
			return func() { _ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN); _ = f.Close() }, nil
		}
		if !errors.Is(err, syscall.EWOULDBLOCK) {
			f.Close()
			return nil, err
		}
		select {
		case <-ctx.Done():
			f.Close()
			return nil, ctx.Err()
		case <-time.After(20 * time.Millisecond):
		}
	}
}
